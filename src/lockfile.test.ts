import { spawnSync } from 'child_process';
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from 'fs';
import { tmpdir } from 'os';
import { dirname, join } from 'path';

import { parsePRDiff } from './diff';
import { formatLockfileChanges, isParsedLockfile, lockfileSignals, readLockfileChanges } from './lockfile';
import { ParsedDiff } from './types';

/** Diffs two versions of a lockfile with git, as a PR diff shows them. `null` stands for a missing file. */
function diffOf(path: string, base: string | null, head: string | null): ParsedDiff {
  const dir = mkdtempSync(join(tmpdir(), 'lockfile-'));
  try {
    const write = (side: string, text: string | null) => {
      if (text === null) return '/dev/null';
      mkdirSync(dirname(join(dir, side, path)), { recursive: true });
      writeFileSync(join(dir, side, path), text);
      return `${side}/${path}`;
    };
    return parsePRDiff(spawnSync('git', ['diff', '--no-index', '--no-prefix', write('a', base), write('b', head)], { cwd: dir, encoding: 'utf-8' }).stdout);
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

function read(path: string, base: string | null, head: string | null) {
  return readLockfileChanges(diffOf(path, base, head), new Map(head === null ? [] : [[path, head]]));
}

