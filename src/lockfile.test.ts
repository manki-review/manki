describe('isParsedLockfile', () => {
  it.each([
    ['Cargo.lock', true], ['crates/sub/Cargo.lock', true], ['package-lock.json', true], ['npm-shrinkwrap.json', true],
    ['web/yarn.lock', true], ['pnpm-lock.yaml', true], ['poetry.lock', false], ['.github/workflows/actions.lock', false], ['Cargo.toml', false],
  ])('%s: %s', (path, parsed) => {
    expect(isParsedLockfile(path)).toBe(parsed);
  });
});

describe('readLockfileChanges', () => {
  it('lists the package changes of a Cargo.lock and flags the ones that need a reason', () => {
    const lockfiles = read('Cargo.lock', CARGO_BASE, CARGO_HEAD);

    expect(formatLockfileChanges(lockfiles)).toBe([
      'Cargo.lock',
      '  changed app 0.1.0 (line 9)',
      '    added dependencies "bls"',
      '  added bls 0.2.0 from git+https://github.com/example/bls?rev=1a2b3c4#1a2b3c4d5e6f7a8b9c0d1e2f3a4b5c6d7e8f9a0b (line 16) [git source]',
      '  changed hex 0.4.3, checksum changed (line 25) [checksum changed without a version change]',
      '  updated serde 1.0.210 -> 1.0.215 (line 29)',
      '  updated untrusted 0.9.0 -> 0.7.1 (line 35) [downgrade]',
      `  changed zeroize 1.8.1, source ${CRATES_IO} -> sparse+https://crates.example.com/index/ (line 42) [source changed]`,
    ].join('\n'));
    expect(lockfileSignals(lockfiles)).toEqual([
      expect.objectContaining({ tool: 'Manki', ruleId: 'lockfile-change', severity: 'warning', file: 'Cargo.lock', line: 16, source: 'lockfile', message: expect.stringContaining(': git source. ') }),
      expect.objectContaining({ line: 25, message: expect.stringMatching(/^changed hex 0\.4\.3, checksum changed: checksum changed without a version change\. /) }),
      expect.objectContaining({ line: 35, message: expect.stringMatching(/^updated untrusted 0\.9\.0 -> 0\.7\.1: downgrade\. /) }),
      expect.objectContaining({ line: 42, message: expect.stringContaining(': source changed. ') }),
    ]);
  });

  it('flags a new commit of a git dependency, but not a git dependency whose source stays', () => {
    const git = (rev: string, deps: string) => `version = 4\n\n[[package]]\nname = "bls"\nversion = "0.2.0"\nsource = "git+https://github.com/example/bls?branch=main#${rev}"\ndependencies = [\n${deps}]\n`;

    expect(formatLockfileChanges(read('Cargo.lock', git('aaaa', ' "hex",\n'), git('bbbb', ' "hex",\n')))).toBe([
      'Cargo.lock',
      '  changed bls 0.2.0, source git+https://github.com/example/bls?branch=main#aaaa -> git+https://github.com/example/bls?branch=main#bbbb (line 6) [git source]',
    ].join('\n'));
    expect(lockfileSignals(read('Cargo.lock', git('aaaa', ' "hex",\n'), git('aaaa', ' "hex",\n "serde",\n')))).toEqual([]);
  });

  it('lists a package-lock.json with the source of each added package, and flags a tarball from another host whose checksum changed', () => {
    const lock = (packages: string, deps: string) => `{
  "name": "app",
  "version": "1.0.0",
  "lockfileVersion": 3,
  "requires": true,
  "packages": {
    "": {
      "name": "app",
      "version": "1.0.0",
      "dependencies": {
${deps}
      }
    },
${packages}
  }
}
`;
    const leftPad = (resolved: string, integrity: string) => `    "node_modules/left-pad": {
      "version": "1.3.0",
      "resolved": "${resolved}",
      "integrity": "${integrity}"
    },`;
    const lodash = (version: string, integrity: string) => `    "node_modules/lodash": {
      "version": "${version}",
      "resolved": "https://registry.npmjs.org/lodash/-/lodash-${version}.tgz",
      "integrity": "${integrity}"
    }`;
    const base = lock([
      leftPad('https://registry.npmjs.org/left-pad/-/left-pad-1.3.0.tgz', 'sha512-XI5MPzVNApjAyhQzphX8BkmKsKUxD4LdyK24iZeQEDl7rLmmHT4Ii4kZ0f'),
      lodash('4.17.20', 'sha512-PlhdFcillOINfeV7Ni6oF1TAEayyZBoZ8bcshTHqOYJYlrqzRK5hagpagky5o4HfCzzd1TRkXPMFq6cKk9rGmA=='),
    ].join('\n'), '        "left-pad": "^1.3.0",\n        "lodash": "^4.17.20"');
    const isOdd = `    "node_modules/is-odd": {
      "version": "3.0.1",
      "resolved": "https://npm.example.net/is-odd/-/is-odd-3.0.1.tgz",
      "integrity": "sha512-CQpnWPrDwmP1+SMHXZhtLtJv90yiyVfluGsX5iNCVkrhQtU3TQHsUWPG9wkdk9Lgd5yNpAg9jQEo90CBaXgWMA==",
      "license": "MIT"
    },`;
    const head = lock([
      isOdd,
      leftPad('https://evil.example.com/left-pad-1.3.0.tgz', 'sha512-AAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAA'),
      lodash('4.17.21', 'sha512-v2kDEe57lecTulaDIuNTPy3Ry4gLGJ6Z1O3vE1krgXZNrsQ+LFTGHVxVjcXPs17LhbZVGedAJv8XZ1tvj5FvSg=='),
    ].join('\n'), '        "is-odd": "^3.0.1",\n        "left-pad": "^1.3.0",\n        "lodash": "^4.17.21"');

    const lockfiles = read('package-lock.json', base, head);

    expect(formatLockfileChanges(lockfiles)).toBe([
      'package-lock.json',
      '  changed app 1.0.0 (line 11)',
      '    added dependencies.is-odd = ^3.0.1',
      '    changed dependencies.lodash: ^4.17.20 -> ^4.17.21',
      '  added is-odd 3.0.1 from https://npm.example.net/is-odd/-/is-odd-3.0.1.tgz (line 16)',
      '    added license = MIT',
      '  changed left-pad 1.3.0, source https://registry.npmjs.org/left-pad/-/left-pad-1.3.0.tgz -> https://evil.example.com/left-pad-1.3.0.tgz, checksum changed (line 24)'
        + ' [source changed, source does not name this package and version, checksum changed without a version change]',
      '  updated lodash 4.17.20 -> 4.17.21 (line 28)',
    ].join('\n'));
    expect(lockfileSignals(lockfiles).map(s => [s.file, s.line])).toEqual([['package-lock.json', 24]]);
  });

  it('lists a bump in an npm lockfile version 2 once, without its legacy `dependencies` map', () => {
    const lock = (version: string) => JSON.stringify({
      name: 'app', lockfileVersion: 2, requires: true,
      packages: { 'node_modules/lodash': { version, resolved: `https://registry.npmjs.org/lodash/-/lodash-${version}.tgz`, integrity: `sha512-${version}` } },
      dependencies: { lodash: { version, resolved: `https://registry.npmjs.org/lodash/-/lodash-${version}.tgz`, integrity: `sha512-${version}` } },
    }, null, 2);

    expect(formatLockfileChanges(read('package-lock.json', lock('4.17.20'), lock('4.17.21')))).toBe('package-lock.json\n  updated lodash 4.17.20 -> 4.17.21 (line 7)');
  });

  it('lists a Yarn 1 lockfile with scoped packages, and flags a downgrade', () => {
    const lock = (frame: string, lodash: string) => `# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.
# yarn lockfile v1


"@babel/code-frame@^7.0.0":
  version "${frame}"
  resolved "https://registry.yarnpkg.com/@babel/code-frame/-/code-frame-${frame}.tgz#dad9af6a5b8f0e2b"
  integrity sha512-${frame}
  dependencies:
    "@babel/highlight" "^${frame}"

lodash@^4.17.0:
  version "${lodash}"
  resolved "https://registry.yarnpkg.com/lodash/-/lodash-${lodash}.tgz#679591c564c3bffaae8454cf0b3df370c3d6911c"
  integrity sha512-${lodash}
`;

    const lockfiles = read('yarn.lock', lock('7.12.13', '4.17.21'), lock('7.16.0', '4.17.20'));

    expect(formatLockfileChanges(lockfiles)).toBe([
      'yarn.lock',
      '  updated @babel/code-frame 7.12.13 -> 7.16.0 (line 6)',
      '    changed dependencies.@babel/highlight: ^7.12.13 -> ^7.16.0',
      '  updated lodash 4.17.21 -> 4.17.20 (line 13) [downgrade]',
    ].join('\n'));
  });

  it('lists a Yarn 2 lockfile, and flags a package from a git repository', () => {
    const lock = (extra: string, deps: string) => `# This file is generated by running "yarn install" inside your project.
# Manual changes might be lost - proceed with caution!

__metadata:
  version: 8
  cacheKey: 10c0

"app@workspace:.":
  version: 0.0.0-use.local
  resolution: "app@workspace:."
  dependencies:
${deps}
  languageName: unknown
  linkType: soft
${extra}
"lodash@npm:^4.17.21":
  version: 4.17.21
  resolution: "lodash@npm:4.17.21"
  checksum: 10c0/d8cbea072bb08655bb4c989da418994b073a608dffa608b09ac04b43a791b12a
  languageName: node
  linkType: hard
`;
    const leftPad = `
"left-pad@https://github.com/example/left-pad.git#commit=4f3c2b1a":
  version: 1.3.0
  resolution: "left-pad@https://github.com/example/left-pad.git#commit=4f3c2b1a"
  checksum: 10c0/0123456789abcdef
  languageName: node
  linkType: hard
`;

    const lockfiles = read('yarn.lock', lock('', '    lodash: "npm:^4.17.21"'), lock(leftPad, '    left-pad: "https://github.com/example/left-pad.git"\n    lodash: "npm:^4.17.21"'));

    expect(formatLockfileChanges(lockfiles)).toBe([
      'yarn.lock',
      '  changed app 0.0.0-use.local (line 12)',
      '    added dependencies.left-pad = https://github.com/example/left-pad.git',
      '  added left-pad 1.3.0 from https://github.com/example/left-pad.git#commit=4f3c2b1a (line 17) [git source]',
      '    added languageName = node',
      '    added linkType = hard',
      '    added requested = left-pad@https://github.com/example/left-pad.git#commit=4f3c2b1a',
    ].join('\n'));
  });

  it('lists a pnpm lockfile with its snapshots and importers', () => {
    const lock = (reactDom: string, integrity: string, scheduler: boolean) => `lockfileVersion: '9.0'

settings:
  autoInstallPeers: true
  excludeLinksFromLockfile: false

importers:

  .:
    dependencies:
      react-dom:
        specifier: ^${reactDom}
        version: ${reactDom}(react@18.2.0)

packages:

  loose-envify@1.4.0:
    resolution: {integrity: ${integrity}}
    hasBin: true

  react-dom@${reactDom}:
    resolution: {integrity: sha512-${reactDom}}
    peerDependencies:
      react: ^18.2.0

  react@18.2.0:
    resolution: {integrity: sha512-react}
    engines: {node: '>=0.10.0'}
${scheduler ? `
  scheduler@0.23.2:
    resolution: {integrity: sha512-scheduler}
` : ''}
snapshots:

  loose-envify@1.4.0: {}

  react-dom@${reactDom}(react@18.2.0):
    dependencies:
      loose-envify: 1.4.0
      react: 18.2.0${scheduler ? '\n      scheduler: 0.23.2' : ''}

  react@18.2.0:
    dependencies:
      loose-envify: 1.4.0
${scheduler ? '\n  scheduler@0.23.2:\n    dependencies:\n      loose-envify: 1.4.0\n' : ''}`;

    const lockfiles = read('pnpm-lock.yaml', lock('18.2.0', 'sha512-old', false), lock('18.3.1', 'sha512-new', true));

    expect(formatLockfileChanges(lockfiles)).toBe([
      'pnpm-lock.yaml',
      '  changed importer . (line 12)',
      '    changed dependencies.react-dom.specifier: ^18.2.0 -> ^18.3.1',
      '    changed dependencies.react-dom.version: 18.2.0(react@18.2.0) -> 18.3.1(react@18.2.0)',
      '  changed loose-envify 1.4.0, checksum changed (line 18) [checksum changed without a version change]',
      '  updated react-dom 18.2.0 -> 18.3.1 (line 21)',
      '    added snapshot(react@18.2.0).dependencies.scheduler = 0.23.2',
      '  added scheduler 0.23.2 from registry (line 30)',
      '    added snapshot.dependencies.loose-envify = 1.4.0',
    ].join('\n'));
  });

  it('lists every package of an added lockfile and of a deleted one', () => {
    const lock = `version = 4\n\n[[package]]\nname = "hex"\nversion = "0.4.3"\nsource = "${CRATES_IO}"\nchecksum = "7f24"\n`;

    expect(formatLockfileChanges(read('Cargo.lock', null, lock))).toBe(`Cargo.lock\n  added hex 0.4.3 from ${CRATES_IO} (line 3)\n  added lockfile settings\n    added version = 4`);
    expect(formatLockfileChanges(read('Cargo.lock', lock, null))).toBe('Cargo.lock\n  removed hex 0.4.3\n  removed lockfile settings');
  });

  it('says so when a lockfile change moves no package', () => {
    expect(formatLockfileChanges(read('Cargo.lock', `# old\nversion = 4\n`, `# new\nversion = 4\n`))).toBe('Cargo.lock\n  no package changes');
  });

  it('keeps a value from the PR on one line', () => {
    const lock = (name: string) => `{\n  "lockfileVersion": 3,\n  "packages": {\n    "node_modules/a": {\n      "name": ${JSON.stringify(name)},\n      "version": "1.0.0"\n    }\n  }\n}\n`;

    expect(formatLockfileChanges(read('package-lock.json', lock('a'), lock('a\n  added evil 1.0.0')))).not.toMatch(/\n {2}added evil/);
  });

  it.each([
    ['the head cannot be read', 'Cargo.lock', CARGO_BASE, CARGO_HEAD, new Map<string, string>()],
    ['the head does not match the diff', 'Cargo.lock', CARGO_BASE, CARGO_HEAD, new Map([['Cargo.lock', CARGO_HEAD.replace('bls', 'blz')]])],
    ['a Cargo.lock holds a table Manki does not read', 'Cargo.lock', 'version = 4\n', 'version = 4\n\n[metadata]\n"checksum hex 0.4.3" = "7f24"\n', undefined],
    ['a Cargo.lock value is an inline table', 'Cargo.lock', 'version = 4\n', 'version = 4\nsource = { git = "x" }\n', undefined],
    ['the legacy `dependencies` map of an npm lockfile names another artifact than `packages`', 'package-lock.json',
      '{\n  "lockfileVersion": 2,\n  "packages": {"node_modules/a": {"version": "1.0.0"}},\n  "dependencies": {"a": {"version": "1.0.0"}}\n}\n',
      '{\n  "lockfileVersion": 2,\n  "packages": {"node_modules/a": {"version": "1.0.0"}},\n  "dependencies": {"a": {"version": "1.0.0", "resolved": "https://evil.example.com/a.tgz"}}\n}\n', undefined],
    ['a package-lock.json has no `packages` map', 'package-lock.json', '{\n  "lockfileVersion": 1\n}\n', '{\n  "lockfileVersion": 1,\n  "dependencies": {}\n}\n', undefined],
    ['a Yarn 1 line is not a key and value', 'yarn.lock', 'a@^1:\n  version "1.0.0"\n', 'a@^1:\n  version "1.0.0"\n  evil\n', undefined],
    ['a pnpm snapshot has no package', 'pnpm-lock.yaml', "lockfileVersion: '9.0'\n", "lockfileVersion: '9.0'\nsnapshots:\n  a@1.0.0: {}\n", undefined],
    ['a YAML lockfile uses an alias', 'pnpm-lock.yaml', "lockfileVersion: '9.0'\n", "lockfileVersion: '9.0'\nsettings: &s {a: 1}\nother: *s\n", undefined],
  ])('leaves a lockfile unread when %s', (_label, path, base, head, heads) => {
    expect(readLockfileChanges(diffOf(path, base, head), heads ?? new Map([[path, head]]))).toEqual([]);
  });

  it('leaves the lockfiles past the size budget unread, and reads the ones before it', () => {
    const many = (count: number) => `version = 4\n${Array.from({ length: count }, (_, i) => `\n[[package]]\nname = "crate-${i}"\nversion = "1.0.0"\nsource = "${CRATES_IO}"\n`).join('')}`;
    const diff = diffOf('a/Cargo.lock', null, many(10));
    const big = diffOf('b/Cargo.lock', null, many(2000));

    const lockfiles = readLockfileChanges({ ...diff, files: [...diff.files, ...big.files] }, new Map([['a/Cargo.lock', many(10)], ['b/Cargo.lock', many(2000)]]));

    expect(lockfiles.map(l => l.path)).toEqual(['a/Cargo.lock']);
  });
});
